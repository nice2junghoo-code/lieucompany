export type Model = {
  id: string
  name: string
  tagline: string
  // longer detail-page paragraph shown below the tagline — filled in per model
  description?: string
  categories: string[]
  image: string
  // scales the product photo up within its card — use when the source photo
  // frames the machine smaller than the others (e.g. wider multi-part shots)
  imageScale?: number
  // overrides the auto ER/GR badge with custom text — for non-roaster products
  badgeLabel?: string
  // overrides the default 18px name size — for longer names that need to fit on one line
  nameTextClass?: string
  // detail-page spec table — filled in per model as the info comes in.
  // `order` optionally overrides desktop (sm+) grid position only — mobile
  // always follows array order — for cases where two rows should swap
  // columns on desktop without changing the single-column mobile order.
  specs?: { label: string; value: string; order?: number }[]
  // grouped spec tables (each with its own heading) — used instead of
  // `specs` when a model has multiple variants with separate spec sets
  specGroups?: { heading: string; rows: { label: string; value: string }[] }[]
  // detail-page bullet list of feature highlights
  features?: string[]
  // detail-page color swatches (hex)
  colors?: string[]
  // full-width "Colors" section at the bottom of the detail page: big photo that
  // swaps per selected swatch tile. When set, the small `colors` circles are hidden.
  colorOptions?: { name: string; hex: string; image?: string }[]
  // "제원" showcase below the Colors section: product photo with dimension lines
  // (width/height shown on the photo) above the spec grid built from `specs`
  // `featuresBelow` moves the red-bullet feature list from the top-right column to the bottom of this section
  // `hideTopSpecs` removes the small spec table next to the product photo at the top
  // `noticeBeforeColors` moves the "공식 파트너" box out of the top grid to a full-width row just above the Colors section
  // `buttonsInMain` moves the 구매 상담 신청 / 납품·설치 사례 더보기 buttons out of that box to the bottom of the top-right column
  // `heroLayout` replaces the top photo/title grid with the home-page hero look: centered title + `heroTagline`,
  // big product photo on the light gradient, a 투입량 / 전압 / 크기 stat row (from `specs`) and the CTA buttons underneath
  specShowcase?: {
    width: string
    height: string
    featuresBelow?: boolean
    hideTopSpecs?: boolean
    noticeBeforeColors?: boolean
    buttonsInMain?: boolean
    heroLayout?: boolean
    heroTagline?: string
    // price block under the tagline: big amount + small suffix on one line, optional caption below
    heroPrice?: { amount: string; suffix?: string; caption?: string }
    // section after 주요 기능 that reuses a table model's tagline, photo and one of its spec groups (matched by heading)
    // `specTitle` is the heading above the spec rows (same style as the model-name heading above the 제원 list)
    // `image` replaces the table model's own photo (e.g. a composite with the roaster sitting on the table)
    table?: { modelId: string; specHeading: string; title: string; specTitle: string; image?: string }
    // card row under Colors (like a "recommended models" list): one card per variant, photo taken from the model with `modelId`;
    // a row with a `label` shows it on the left, rows without one are plain lines on the right; "자세히보기" links to /products/{modelId}
    lineup?: {
      title: string
      items: {
        modelId: string
        name: string
        price: string
        vatNote: string
        rows: { label?: string; text: string }[]
      }[]
    }
    // photo gallery under the table section: first photo large, 2-column grid on mobile; with exactly 8 photos the 6th is wide (fills the grid),
    // with 9 photos all the others are squares (fills 3 rows on PC); with 3 photos: 3 equal squares in one row on PC
    gallery?: { title: string; images: string[] }
    // price sheet under the gallery, laid out like the printed price list: 구분 / 판매가격 / 사양 및 제원 / 추가 선택품목
    // each `specLines` entry is one line made of parts; a part with a `label` renders that label in bold
    // one `rows` entry per variant (e.g. 기본형 / B80C / B80S) sharing the 구분 cell on the left; a part with `bold` is rendered bold
    price?: {
      title: string
      subtitle: string
      type: { code: string; label: string }
      optionsNote: string
      rows: {
        name?: string
        amount: string
        vatNote: string
        specLines: { label?: string; text: string; bold?: boolean }[][]
        options: { name: string; price?: string; sub?: string }[]
      }[]
    }
    // size classes for the hero photo (max-width steps); defaults to the B30S sizing
    heroImageClass?: string
  }
  // detail-page component gallery — photo + title/subtitle/description per part
  detailGallery?: { title: string; subtitle?: string; description: string; image?: string }[]
}

